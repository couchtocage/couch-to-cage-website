drop policy if exists "Public submit applications" on public.applications;
drop policy if exists "Admins manage applications" on public.applications;

create policy "Public can read published events"
on public.events for select to anon, authenticated
using (is_published = true or public.is_ctc_admin());

create policy "Admins manage events"
on public.events for all to authenticated
using (public.is_ctc_admin())
with check (public.is_ctc_admin());

create policy "Public can read published gallery"
on public.gallery_items for select to anon, authenticated
using (is_published = true or public.is_ctc_admin());

create policy "Admins manage gallery"
on public.gallery_items for all to authenticated
using (public.is_ctc_admin())
with check (public.is_ctc_admin());

create policy "Public can read site settings"
on public.site_settings for select to anon, authenticated
using (true);

create policy "Admins manage site settings"
on public.site_settings for all to authenticated
using (public.is_ctc_admin())
with check (public.is_ctc_admin());

create policy "Admins can view admin list"
on public.admin_users for select to authenticated
using (user_id = auth.uid() or public.is_ctc_admin());

create policy "Public submit applications"
on public.applications for insert to anon, authenticated
with check (true);

create policy "Admins manage applications"
on public.applications for all to authenticated
using (public.is_ctc_admin())
with check (public.is_ctc_admin());


