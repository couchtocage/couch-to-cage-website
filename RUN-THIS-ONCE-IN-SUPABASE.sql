alter table public.applications add column if not exists fighter_level text;

-- 2) Security helper
create or replace function public.is_ctc_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users where user_id = auth.uid()
  );
$$;

grant execute on function public.is_ctc_admin() to anon, authenticated;

