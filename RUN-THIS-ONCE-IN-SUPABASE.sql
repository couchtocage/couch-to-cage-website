-- 4) Public media bucket and upload policies
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'ctc-media',
  'ctc-media',
  true,
  10485760,
  array['image/jpeg','image/png','image/webp','image/gif']
)
on conflict (id) do update
set public = true,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Public read CTC media" on storage.objects;
drop policy if exists "Admins upload CTC media" on storage.objects;
drop policy if exists "Admins update CTC media" on storage.objects;
drop policy if exists "Admins delete CTC media" on storage.objects;

create policy "Public read CTC media"
on storage.objects for select to public
using (bucket_id = 'ctc-media');

create policy "Admins upload CTC media"
on storage.objects for insert to authenticated
with check (bucket_id = 'ctc-media' and public.is_ctc_admin());

create policy "Admins update CTC media"
on storage.objects for update to authenticated
using (bucket_id = 'ctc-media' and public.is_ctc_admin())
with check (bucket_id = 'ctc-media' and public.is_ctc_admin());

create policy "Admins delete CTC media"
on storage.objects for delete to authenticated
using (bucket_id = 'ctc-media' and public.is_ctc_admin());

